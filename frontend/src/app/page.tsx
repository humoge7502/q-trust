/**
 * Public links to the records the demo seed registered on Base Sepolia.
 * Regenerated by `node backend/scripts/seed-demo-records.mjs`; renders nothing
 * until real asset IDs exist, so the build never depends on live seeding.
 */
function DemoRecords() {
  const records = demoRecords.records.filter((record) => record.assetId);
  if (!records.length) return null;
  return (
    <div className="mt-3 flex flex-wrap items-center gap-2 px-1 text-[11px] text-night-ink-soft">
      <span className="uppercase tracking-[0.16em]">Live on-chain records</span>
      {records.map((record) => (
        <Link
          key={record.assetId}
          href={`/v/${record.assetId}`}
          className="rounded-full border border-white/15 px-2.5 py-1 font-medium text-night-ink-soft transition hover:border-quantum-soft hover:text-quantum-soft focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-quantum-soft"
        >
          {record.label.replace("Q-Trust ", "")}
        </Link>
      ))}
    </div>
  );
}

