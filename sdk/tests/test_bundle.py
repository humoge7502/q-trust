"""Cross-language verification of qtrust.certification.v1 bundles.

The fixture is generated by the TypeScript backend
(``npm run certify:fixture``) with a fixed key and clock. A passing test here
proves the two implementations canonicalise and hash identically — the same
property the VC service relies on.
"""
from __future__ import annotations

import copy
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

from qtrust.bundle import (
    BUNDLE_SCHEMA,
    bundle_digest,
    evidence_leaf_hash,
    merkle_root,
    verify_bundle,
    verify_bundle_file,
)

FIXTURE = Path(__file__).parent / "fixtures" / "certification_bundle.json"
NOW = datetime(2026, 10, 24, 12, 0, 0, tzinfo=timezone.utc)


@pytest.fixture()
def bundle() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_fixture_verifies_offline(bundle):
    result = verify_bundle(bundle, now=NOW)
    assert result.valid, result.reasons
    assert result.reasons == []
    assert result.checked.model_dump() == {
        "structure": True,
        "digest": True,
        "merkle": True,
        "signature": True,
        "validity": True,
    }
    assert result.issuer.startswith("did:key:z")
    assert result.subject == bundle["subject"]["org"]
    assert result.verdict == "CERTIFIED"
    assert result.expired is False
    assert result.chain_anchor == "skipped"


def test_fixture_file_helper(bundle, tmp_path):
    path = tmp_path / "bundle.json"
    path.write_text(json.dumps(bundle), encoding="utf-8")
    assert verify_bundle_file(str(path), now=NOW).valid


def test_digest_matches_bundle(bundle):
    assert bundle["digest"] == bundle_digest(bundle)


def test_tampered_evidence_record_fails_closed(bundle):
    tampered = copy.deepcopy(bundle)
    tampered["evidence"]["leaves"][0]["record"]["host"] = "attacker.example"
    result = verify_bundle(tampered, now=NOW)
    assert not result.valid
    assert not result.checked.digest
    assert not result.checked.merkle
    assert any("digest mismatch" in r for r in result.reasons)


def test_tampered_claim_fails_closed(bundle):
    tampered = copy.deepcopy(bundle)
    tampered["claims"]["asset_count"] = 9999
    result = verify_bundle(tampered, now=NOW)
    assert not result.valid
    assert not result.checked.signature
    assert not result.checked.digest


def test_bad_signature_fails_while_commitments_still_match(bundle):
    tampered = copy.deepcopy(bundle)
    proof = tampered["proof"]["proofValue"]
    tampered["proof"]["proofValue"] = ("00" if proof[:2] != "00" else "11") + proof[2:]
    result = verify_bundle(tampered, now=NOW)
    assert not result.valid
    assert result.checked.digest
    assert result.checked.merkle
    assert not result.checked.signature


def test_dropped_leaf_fails_merkle_check(bundle):
    tampered = copy.deepcopy(bundle)
    tampered["evidence"]["leaves"].pop()
    tampered["evidence"]["leaf_count"] -= 1
    result = verify_bundle(tampered, now=NOW)
    assert not result.valid
    assert not result.checked.merkle
    assert any("Merkle root mismatch" in r for r in result.reasons)


def test_expiry_and_not_yet_valid(bundle):
    expiry = datetime.fromisoformat(bundle["valid_until"].replace("Z", "+00:00"))
    expired = verify_bundle(bundle, now=expiry + timedelta(seconds=1))
    assert not expired.valid and expired.expired

    start = datetime.fromisoformat(bundle["valid_from"].replace("Z", "+00:00"))
    early = verify_bundle(bundle, now=start - timedelta(seconds=1))
    assert not early.valid and not early.checked.validity


def test_pinned_trust_anchor(bundle):
    assert verify_bundle(bundle, now=NOW, trust_anchor_did=bundle["issuer"]).valid
    other = verify_bundle(bundle, now=NOW, trust_anchor_did="did:key:zOther")
    assert not other.valid
    assert any("trust anchor" in r for r in other.reasons)


def test_rejects_non_bundles(bundle):
    for raw in (None, [], {}, {"schema": "other"}, {**bundle, "schema": "other"}):
        assert not verify_bundle(raw).valid
    missing = {k: v for k, v in bundle.items() if k != "proof"}
    result = verify_bundle(missing)
    assert not result.valid
    assert any("missing required fields" in r for r in result.reasons)


def test_merkle_is_order_independent(bundle):
    hashes = [evidence_leaf_hash(leaf) for leaf in bundle["evidence"]["leaves"]]
    assert merkle_root(hashes) == merkle_root(list(reversed(hashes)))
    assert merkle_root(hashes) == bundle["evidence"]["merkle_root"]
    assert merkle_root([]).startswith("0x")


def test_schema_constant_is_pinned(bundle):
    assert bundle["schema"] == BUNDLE_SCHEMA
