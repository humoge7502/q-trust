"""Property tests for certification bundles: tamper-evidence and fail-closed.

The fixture is generated by the TypeScript backend, so these properties also
exercise the cross-language canonicalisation contract on arbitrary mutations.
"""
from __future__ import annotations

import copy
import json
from datetime import datetime, timezone
from pathlib import Path

from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st

from qtrust.bundle import (
    BUNDLE_SCHEMA,
    bundle_digest,
    evidence_leaf_hash,
    merkle_root,
    verify_bundle,
)

FIXTURE = Path(__file__).parent / "fixtures" / "certification_bundle.json"
NOW = datetime(2026, 10, 24, 12, 0, 0, tzinfo=timezone.utc)

# (path, kind) — mutations outside `proof`, which is excluded from both the
# digest and the signature payload by design.
MUTATION_PATHS = [
    ("bundle_id", "text"),
    ("subject.org", "text"),
    ("verdict", "text"),
    ("issued_at", "text"),
    ("valid_from", "text"),
    ("valid_until", "text"),
    ("claims.asset_count", "int"),
    ("claims.migration_counts.verified", "int"),
    ("evidence.merkle_root", "text"),
    ("evidence.leaf_count", "int"),
    ("anchor.block_hash", "text"),
    ("anchor.block_number", "int"),
    ("digest", "text"),
]


def _load() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _walk_set(doc: dict, path: str, value) -> None:
    parts = path.split(".")
    node = doc
    for part in parts[:-1]:
        node = node[part]
    node[parts[-1]] = value


def _walk_get(doc: dict, path: str):
    node = doc
    for part in path.split("."):
        node = node[part]
    return node


_VALUE = st.one_of(st.text(max_size=40), st.integers(min_value=-10_000, max_value=10_000))


@given(path=st.sampled_from(MUTATION_PATHS), value=_VALUE)
@settings(max_examples=60, deadline=None, suppress_health_check=[HealthCheck.function_scoped_fixture])
def test_any_mutation_outside_proof_is_rejected(path, value):
    target, _kind = path
    doc = _load()
    original = _walk_get(doc, target)
    _walk_set(doc, target, value)
    if json.dumps(original, sort_keys=True) == json.dumps(value, sort_keys=True):
        return  # no-op mutation
    result = verify_bundle(doc, now=NOW)
    assert not result.valid


@given(index=st.integers(min_value=0, max_value=3))
@settings(max_examples=20, deadline=None)
def test_any_tampered_evidence_record_is_rejected(index):
    doc = _load()
    leaf = doc["evidence"]["leaves"][index % len(doc["evidence"]["leaves"])]
    leaf["record"]["injected"] = {"by": "attacker"}
    result = verify_bundle(doc, now=NOW)
    assert not result.valid
    assert not result.checked.merkle


@given(key=st.sampled_from(list(_load().keys())))
@settings(max_examples=25, deadline=None)
def test_dropping_a_top_level_field_is_rejected(key):
    doc = _load()
    del doc[key]
    assert not verify_bundle(doc, now=NOW).valid


@given(digest=st.binary(min_size=1, max_size=64))
@settings(max_examples=40, deadline=None)
def test_merkle_root_changes_when_any_digest_changes(digest):
    baseline = [
        evidence_leaf_hash({"kind": "asset", "id": "a", "digest": "0" * 64}),
        evidence_leaf_hash({"kind": "asset", "id": "b", "digest": "0" * 64}),
    ]
    changed = [
        evidence_leaf_hash({"kind": "asset", "id": "a", "digest": digest.hex()}),
        evidence_leaf_hash({"kind": "asset", "id": "b", "digest": "0" * 64}),
    ]
    if digest.hex() != "0" * 64:
        assert merkle_root(baseline) != merkle_root(changed)


@given(payload=st.recursive(
    st.one_of(st.none(), st.booleans(), st.integers(), st.text(max_size=12)),
    lambda children: st.one_of(
        st.lists(children, max_size=3),
        st.dictionaries(st.text(max_size=6), children, max_size=3),
    ),
    max_leaves=12,
))
@settings(max_examples=80, deadline=None)
def test_verifier_never_raises_on_arbitrary_json(payload):
    result = verify_bundle(payload, now=NOW)
    assert result.valid is False


@given(asset_count=st.integers(min_value=0, max_value=10**6))
@settings(max_examples=20, deadline=None)
def test_claim_mutation_breaks_the_digest(asset_count):
    doc = _load()
    doc["claims"]["asset_count"] = asset_count
    assert doc["digest"] != bundle_digest(doc)


def test_fixture_is_structurally_complete():
    doc = _load()
    assert doc["schema"] == BUNDLE_SCHEMA
    assert copy.deepcopy(doc) == doc
    assert verify_bundle(doc, now=NOW).valid
